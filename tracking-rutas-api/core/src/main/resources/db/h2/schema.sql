CREATE TABLE IF NOT EXISTS anomalias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envio_id BIGINT NOT NULL REFERENCES pedidos(id_pedido),
    tipo VARCHAR(40) NOT NULL CHECK (tipo IN ('PERMANENCIA_EXCESIVA','INACTIVIDAD_REPARTO','REINTENTOS_ACUMULADOS','SIN_CONFIRMACION_RECEPCION')),
    evento_origen VARCHAR(90) NOT NULL,
    oficina_id BIGINT REFERENCES oficinas_logisticas(id),
    inicio_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    umbral_horas INTEGER CHECK (umbral_horas BETWEEN 1 AND 168),
    intentos INTEGER CHECK (intentos BETWEEN 2 AND 3),
    estado VARCHAR(12) NOT NULL CHECK (estado IN ('ACTIVA','RESUELTA','DESCARTADA')),
    clave_activa INTEGER,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    cerrada_en TIMESTAMP WITH TIME ZONE,
    cerrada_por BIGINT REFERENCES usuarios(id),
    origen_cierre VARCHAR(20) CHECK (origen_cierre IN ('SISTEMA','WEB','MOVIL','QR','OFFLINE')),
    CONSTRAINT uk_anomalia_evento UNIQUE (envio_id,tipo,evento_origen),
    CONSTRAINT uk_anomalia_activa UNIQUE (envio_id,tipo,clave_activa),
    CONSTRAINT chk_anomalia_cierre CHECK (
        (estado='ACTIVA' AND clave_activa IS NOT NULL AND clave_activa=1 AND cerrada_en IS NULL AND cerrada_por IS NULL AND origen_cierre IS NULL)
        OR (estado IN ('RESUELTA','DESCARTADA') AND clave_activa IS NULL AND cerrada_en IS NOT NULL
            AND origen_cierre IS NOT NULL AND (origen_cierre='SISTEMA' OR cerrada_por IS NOT NULL)))
);
CREATE INDEX IF NOT EXISTS idx_anomalia_estado_envio ON anomalias(estado,envio_id,id);
