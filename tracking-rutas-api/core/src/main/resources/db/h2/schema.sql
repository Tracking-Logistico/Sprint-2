CREATE TABLE IF NOT EXISTS historial_parametros_anomalia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permanencia_horas INTEGER NOT NULL CHECK (permanencia_horas BETWEEN 1 AND 168),
    inactividad_horas INTEGER NOT NULL CHECK (inactividad_horas BETWEEN 1 AND 168),
    recepcion_horas INTEGER NOT NULL CHECK (recepcion_horas BETWEEN 1 AND 168),
