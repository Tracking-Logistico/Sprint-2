CREATE TABLE parametros_anomalia (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    permanencia_horas INTEGER NOT NULL CHECK (permanencia_horas BETWEEN 1 AND 168),
    inactividad_horas INTEGER NOT NULL CHECK (inactividad_horas BETWEEN 1 AND 168),
    recepcion_horas INTEGER NOT NULL CHECK (recepcion_horas BETWEEN 1 AND 168),
    version BIGINT NOT NULL DEFAULT 0,
    modificado_por BIGINT REFERENCES usuarios(id),
    modificado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    origen VARCHAR(20) NOT NULL CHECK (origen IN ('SISTEMA','WEB','MOVIL','QR','OFFLINE'))
);
