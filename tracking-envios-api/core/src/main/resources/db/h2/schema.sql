CREATE TABLE IF NOT EXISTS historial_asignaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedidos(id_pedido),
    conductor_anterior_id BIGINT REFERENCES usuarios(id),
    conductor_nuevo_id BIGINT NOT NULL REFERENCES usuarios(id),
    operador_id BIGINT REFERENCES usuarios(id),
    accion VARCHAR(20) NOT NULL CHECK (accion IN ('ASIGNACION', 'REASIGNACION')),
    motivo VARCHAR(500),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_historial_asignaciones_pedido ON historial_asignaciones(id_pedido, fecha);
CREATE TABLE IF NOT EXISTS notificaciones_conductor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_conductor BIGINT NOT NULL REFERENCES usuarios(id),
    id_pedido BIGINT NOT NULL REFERENCES pedidos(id_pedido),
    mensaje VARCHAR(255) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    event_id VARCHAR(36) UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_notificaciones_conductor ON notificaciones_conductor(id_usuario_conductor, fecha DESC);

CREATE TABLE IF NOT EXISTS ciudades_logisticas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ciudad_nombre_departamento
    ON ciudades_logisticas (nombre, departamento);

CREATE TABLE IF NOT EXISTS oficinas_logisticas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    ciudad_id BIGINT NOT NULL REFERENCES ciudades_logisticas(id),
    direccion VARCHAR(250) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    email VARCHAR(255),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_oficina_nombre_ciudad
    ON oficinas_logisticas (ciudad_id, nombre);
CREATE UNIQUE INDEX IF NOT EXISTS uk_oficina_direccion_ciudad
    ON oficinas_logisticas (ciudad_id, direccion);

CREATE TABLE IF NOT EXISTS puntos_entrega (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    ciudad_id BIGINT NOT NULL REFERENCES ciudades_logisticas(id),
    oficina_id BIGINT REFERENCES oficinas_logisticas(id),
    direccion VARCHAR(250) NOT NULL,
    descripcion VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_punto_entrega_nombre_ciudad
    ON puntos_entrega (ciudad_id, oficina_id, nombre);
CREATE UNIQUE INDEX IF NOT EXISTS uk_punto_entrega_direccion_ciudad
    ON puntos_entrega (ciudad_id, oficina_id, direccion);

CREATE TABLE IF NOT EXISTS eventos_ubicacion_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento VARCHAR(36) NOT NULL UNIQUE,
    id_pedido BIGINT NOT NULL REFERENCES pedidos(id_pedido),
    numero_tracking VARCHAR(50) NOT NULL,
    etapa VARCHAR(40) NOT NULL,
    estado_pedido VARCHAR(40) NOT NULL,
    ciudad_id BIGINT REFERENCES ciudades_logisticas(id),
    ciudad_nombre VARCHAR(100) NOT NULL,
    oficina_id BIGINT REFERENCES oficinas_logisticas(id),
    oficina_nombre VARCHAR(120),
    punto_entrega_id BIGINT REFERENCES puntos_entrega(id),
    punto_entrega_nombre VARCHAR(120),
    direccion VARCHAR(250),
    vehiculo_id VARCHAR(80),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    origen VARCHAR(20) NOT NULL,
    fecha_evento TIMESTAMP NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    corrige_evento_id BIGINT REFERENCES eventos_ubicacion_pedido(id)
);
CREATE INDEX IF NOT EXISTS idx_evento_ubicacion_pedido_fecha
    ON eventos_ubicacion_pedido(id_pedido, fecha_evento, id);
